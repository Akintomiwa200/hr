import { Bell, CheckCircle2, Clock3, Mail } from "lucide-react";
import { prisma } from "@/lib/prisma";
import { PageHeader, StatCard } from "@/components/ui";
import { PageLiveRefresh } from "@/components/dashboard/page-live-refresh";
import {
  formatPlatformDateTime,
  platformStatusClass,
  platformStatusLabel,
  requirePlatformAdmin,
} from "@/lib/platform-control";

export default async function PlatformDeliveryLogsPage() {
  await requirePlatformAdmin();

  const notifications = await prisma.notification.findMany({
    include: { user: { select: { email: true } } },
    orderBy: { createdAt: "desc" },
    take: 200,
  });

  const read = notifications.filter((notification) => notification.readAt).length;
  const unread = notifications.length - read;

  return (
    <div className="w-full space-y-5">
      <PageLiveRefresh
        types={["notification_updated", "announcement_created", "dashboard_updated"]}
      />
      <PageHeader
        title="Email & notification logs"
        description="Recent in-app notification records generated by the platform."
      />

      <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard label="Notification records" value={notifications.length} icon={Bell} />
        <StatCard label="Read" value={read} icon={CheckCircle2} />
        <StatCard label="Unread" value={unread} icon={Mail} />
        <StatCard
          label="Latest record"
          value={
            notifications[0]
              ? formatPlatformDateTime(notifications[0].createdAt)
              : "—"
          }
          icon={Clock3}
        />
      </div>

      <div className="rounded-xl border border-blue-100 bg-blue-50/70 px-4 py-3 text-sm leading-6 text-blue-900">
        These are in-app notification records. SMTP delivery attempts and bounce
        receipts are not stored by the current model.
      </div>

      <div className="overflow-hidden rounded-2xl border border-gray-100 bg-white shadow-[0_1px_3px_rgba(0,0,0,0.04)]">
        <div className="flex flex-wrap items-center justify-between gap-3 border-b border-gray-100 px-5 py-4">
          <div>
            <h2 className="text-[13px] font-semibold text-gray-900">
              Delivery history
            </h2>
            <p className="mt-1 text-xs text-gray-500">
              {notifications.length
                ? `${notifications.length} records · new notifications appear instantly`
                : "No notification records have been generated yet."}
            </p>
          </div>
          <span className="rounded-full bg-violet-50 px-2.5 py-1 text-[10px] font-semibold text-violet-700">
            LIVE
          </span>
        </div>

        <div className="overflow-x-auto">
          <table className="w-full min-w-[860px] text-left">
            <thead>
              <tr className="border-b border-gray-100 text-[11px] uppercase tracking-wide text-gray-400">
                <th className="px-5 py-3 font-semibold">Notification</th>
                <th className="px-5 py-3 font-semibold">Type</th>
                <th className="px-5 py-3 font-semibold">Recipient</th>
                <th className="px-5 py-3 font-semibold">Status</th>
                <th className="px-5 py-3 font-semibold">Created</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-gray-50">
              {notifications.map((notification) => (
                <tr key={notification.id} className="hover:bg-gray-50/60">
                  <td className="px-5 py-3">
                    <p className="text-[12.5px] font-medium text-gray-900">
                      {notification.title}
                    </p>
                    <p className="max-w-[320px] truncate text-[11px] text-gray-500">
                      {notification.message}
                    </p>
                  </td>
                  <td className="px-5 py-3 text-[12.5px] capitalize text-gray-700">
                    {notification.type}
                  </td>
                  <td className="px-5 py-3 text-[12.5px] text-gray-600">
                    {notification.user.email}
                  </td>
                  <td className="px-5 py-3">
                    <span
                      className={`inline-flex rounded-full px-2.5 py-1 text-[10px] font-semibold ${platformStatusClass(
                        notification.readAt ? "READ" : "QUEUED"
                      )}`}
                    >
                      {notification.readAt
                        ? "READ"
                        : platformStatusLabel("QUEUED")}
                    </span>
                  </td>
                  <td className="whitespace-nowrap px-5 py-3 text-[12px] text-gray-500">
                    {formatPlatformDateTime(notification.createdAt)}
                  </td>
                </tr>
              ))}
              {notifications.length === 0 && (
                <tr>
                  <td
                    colSpan={5}
                    className="px-5 py-12 text-center text-sm text-gray-500"
                  >
                    <Mail className="mx-auto mb-3 h-6 w-6 text-gray-300" />
                    No notification records are present yet.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
